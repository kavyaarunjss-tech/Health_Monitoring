"""Write docs/weekly_advice_review.md: every statement of the weekly card (C1-C2, S1-S12, L1-L4, A1-A14) with its exact text, groups,
condition and source numbers, generated from backend/weekly_advice_rules.json (the file the website uses), for wording review.

usage (project root, aqi env):  python backend\\export_weekly_review.py      (test_weekly.py checks the file is up to date)
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RULES = ROOT / "backend" / "weekly_advice_rules.json"
OUT = ROOT / "docs" / "weekly_advice_review.md"

SECTIONS = [("clean", "C", "Card section \"This week\" (clean weeks only)"),
            ("short_term", "S", "Card section \"This week may affect you\" (short-term)"),
            ("long_term", "L", "Card section \"If this continues\" (long-term awareness, persistent weeks only)"),
            ("actions", "A", "Card section \"What you can do\"")]
LEVEL = {"clean": "clean week (no day Moderate or worse)", "episode": "episode week (1-3 days Moderate or worse)",
         "persistent": "persistent week (>= 4 of 7 days AQI >= 101)"}
GROUP = {"all": "everyone", "healthy": "healthy adult (no condition ticked)", "lung": "lung disease", "heart": "heart disease",
         "child": "child (< 14)", "older": "older adult (>= 60)", "pregnant": "pregnant", "outdoor_work": "outdoor worker",
         "exercise": "athlete / exercises outdoors"}
POLL = {"pm25": "PM2.5", "pm10": "PM10", "no2": "NO2", "so2": "SO2", "o3": "O3", "co": "CO"}


def condition(r):
    parts = [" or ".join(LEVEL[x] for x in r.get("levels", ["clean"]))]          # clean rules: used only on clean weeks (weekly.health)
    if r.get("min_category"):
        parts.append(f"worst day of the week {r['min_category']} or worse"
                     + (f" (healthy adult: {r['min_category_healthy']} or worse)" if r.get("min_category_healthy") else ""))
    if r.get("pollutant"):
        parts.append(f"main pollutant of the week {POLL.get(r['pollutant'], r['pollutant'])}")
    return "; ".join(parts)


def groups(r):
    g = ", ".join(GROUP.get(x, x) for x in r["groups"])
    if r.get("not_groups"):
        g += " (NOT for: " + ", ".join(GROUP.get(x, x) for x in r["not_groups"]) + ")"
    return g


def cell(s):
    return str(s).replace("|", "\\|").replace("\n", " ")


def build():
    import sys
    sys.path.insert(0, str(ROOT / "backend"))
    import weekly
    rules = weekly.RULES                      # texts without the **bold** markers; "marked" keeps them
    n = sum(len(rules[k]) for k, _, _ in SECTIONS)
    lines = ["# Weekly card \"This week's air and your health\": all statements for wording review", "",
             f"Generated by `backend/export_weekly_review.py` from `backend/weekly_advice_rules.json` (the file the website reads), {n} statements.",
             "Do not edit this file by hand: change the JSON (and the matching row in `docs/health_advisory_reference.md` section 8), then re-run the script.",
             "Source numbers refer to the reference list below (same numbers as on the website). \"Basis\" is the exact source wording the statement rests on;",
             "full quotes with pages are in `docs/health_advisory_reference.md` section 8.", "",
             "General rules applied by the code (not per statement): no health text when fewer than 5 of 7 days are valid; the long-term section only on",
             "persistent weeks; every card shows \"General information from public health guidance, not medical advice.\"", ""]
    for key, _, title in SECTIONS:
        lines += [f"## {title}", "", "| id | exact text | shown in bold | groups | condition | sources | basis (source wording) |", "|---|---|---|---|---|---|---|"]
        for r in rules[key]:
            src = "".join(f"[{s}]" for s in r["sources"])
            bold = "; ".join(re.findall(r"\*\*(.+?)\*\*", r["marked"]))
            lines.append(f"| {r['id']} | {cell(r['text'])} | {cell(bold)} | {cell(groups(r))} | {cell(condition(r))} | {src} | {cell(r.get('basis', ''))} |")
        lines.append("")
    changed = [r for k, _, _ in SECTIONS for r in rules[k] if weekly.past_tense(r["text"]) != r["text"]]
    lines += ["## Past-tense wording (live and profile pages when the newest data is more than 24 h old)", "",
              "Replay always uses the wording above (it is relative to the replay clock). With live data older than 24 h the card is titled",
              "\"Last available week (<dates>)\", shows \"Data feed stopped: newest data is <N> h old; this is not the current week.\", the headings become",
              "\"That week\", \"During that week, air like this may affect you\", \"If air like that week's continues\" (intro \"... of those 7 days\") and",
              "\"What you can do\", the trend chip reads \"That week: rising / falling / steady\" (replay: \"Last 7 days: ...\"), and these texts change:", "",
              "| id | past-tense text |", "|---|---|"]
    lines += [f"| {r['id']} | {cell(weekly.past_tense(r['text']))} |" for r in changed]
    lines.append("")
    lines += ["## Notes shown under the limits table", "", f"- India: {rules['notes']['india']}", f"- WHO: {rules['notes']['who']}", "",
              "## Sources (links as used on the card)", ""]
    import sys
    sys.path.insert(0, str(ROOT / "backend"))
    import advice
    for k in sorted(advice.REFERENCES, key=int):
        url = rules["urls"].get(k, "")
        lines.append(f"{k}. {advice.REFERENCES[k]}" + (f" {url}" if url and url not in advice.REFERENCES[k] else ""))
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    OUT.write_text(build(), encoding="utf-8")
    print(f"wrote {OUT}")
